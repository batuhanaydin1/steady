using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Steady.Api.Entities;

namespace Steady.Api.Data.Configurations;

public sealed class TimerPreferencesConfiguration : IEntityTypeConfiguration<TimerPreferences>
{
    public void Configure(EntityTypeBuilder<TimerPreferences> builder)
    {
        builder.ToTable("timer_preferences", table =>
        {
            // Preferences belong to the installation, so there is exactly one row.
            // The database enforces that, rather than trusting every code path to
            // remember it.
            table.HasCheckConstraint("ck_timer_preferences_singleton", "id = 1");

            // The same bounds the API validates. If a future code path skips that
            // validation, PostgreSQL still refuses the write.
            table.HasCheckConstraint(
                "ck_timer_preferences_work_minutes",
                $"work_minutes between {TimerPreferences.WorkMinutesMin} and {TimerPreferences.WorkMinutesMax}");
            table.HasCheckConstraint(
                "ck_timer_preferences_break_minutes",
                $"break_minutes between {TimerPreferences.BreakMinutesMin} and {TimerPreferences.BreakMinutesMax}");
        });

        builder.HasKey(preferences => preferences.Id)
            .HasName("pk_timer_preferences");

        builder.Property(preferences => preferences.Id)
            .HasColumnName("id")
            // The key is chosen by the application, never generated by the store.
            .ValueGeneratedNever();
        builder.Property(preferences => preferences.WorkMinutes)
            .HasColumnName("work_minutes")
            .IsRequired();
        builder.Property(preferences => preferences.BreakMinutes)
            .HasColumnName("break_minutes")
            .IsRequired();
        builder.Property(preferences => preferences.SoundEnabled)
            .HasColumnName("sound_enabled")
            .IsRequired();
        builder.Property(preferences => preferences.NotificationsEnabled)
            .HasColumnName("notifications_enabled")
            .IsRequired();
        builder.Property(preferences => preferences.UpdatedAt)
            .HasColumnName("updated_at")
            .IsRequired();
    }
}
